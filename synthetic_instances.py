if __name__ == "__main__":

    out_dir = "synthetic_data"
    os.makedirs(out_dir, exist_ok=True)

    seed = 2

    for perturbed in [True]:
        synth = generate_synthetic_instances(
            N=100,
            K=5,
            d=20,
            m_core=8,
            n_groups=5,
            n_clusters=10,
            perturbed=perturbed,
            n_vars_perturbed=1,
            noise_concentration=50.0,
            seed=seed,
            verbose=True,
        )

        suffix = "perturbed" if perturbed else "optimal"
        fname = os.path.join(
            out_dir,
            f"synthetic_K5_d20_N100_clusters10_{suffix}_seed_{seed}.pkl")
        with open(fname, "wb") as f:
            pickle.dump(synth, f, protocol=pickle.HIGHEST_PROTOCOL)
        print(f"\nSaved: {fname}\n")
